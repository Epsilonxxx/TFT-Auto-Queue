export type Copy = (typeof copy)["zh-CN"] | (typeof copy)["en-US"];

export function duration(ms: number): string {
  const seconds = Math.max(0, Math.floor(ms / 1000));
  const hours = Math.floor(seconds / 3600);
  return `${hours ? `${String(hours).padStart(2, "0")}:` : ""}${String(Math.floor(seconds / 60) % 60).padStart(2, "0")}:${String(seconds % 60).padStart(2, "0")}`;
}

export function phaseLabel(t: Copy, phase: string): string {
  return t.phases[phase as keyof Copy["phases"]] ?? phase;
}

export function activityLabel(message: string, language: string): string {
  if (language !== "zh-CN") return message;
  if (message.startsWith("Phase: "))
    return `阶段更新：${phaseLabel(copy["zh-CN"], message.slice(7))}`;
  const known: Record<string, string> = {
    "Search started.": "已发起匹配，等待对局确认",
    "Lobby created.": "已创建匹配房间",
    "Ready-check accepted.": "已自动接受对局",
    "Disabled.": "自动匹配已停止",
    "LCU connection recovered.": "客户端连接已恢复",
    "LCU connection unstable, trying recovery...":
      "客户端连接中断，正在自动重试",
    "Force-closed the League game process.": "已结束超时的游戏进程",
    "Requested return to lobby after force-closing the game.":
      "已请求返回房间，等待客户端更新",
    "Detected a League crash dialog and completed the crash-report flow.":
      "已完成崩溃报告处理",
    "Detected a League crash dialog and handled it.": "已处理客户端崩溃弹窗",
    "Post-game: play-again sent.": "结算完成，已请求再来一局",
    "Reconnect command sent.": "已请求重新连接对局",
    "Returned to the League home screen.": "已返回客户端主页",
  };
  if (known[message]) return known[message];
  if (message.startsWith("Enabled for queue:")) return "自动匹配已启动";
  if (message.startsWith("Cycle completed.")) return "对局已完成，统计已更新";
  if (message.startsWith("Post-game requeue delay:"))
    return "正在等待下一轮匹配";
  if (message.startsWith("Same match exceeded"))
    return "单局已超过时限，正在退出并恢复匹配";
  return message;
}
